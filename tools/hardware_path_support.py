# SC-NeuroCore — Write or check the hardware-path supported set

"""Write or check the table of catalogue models the one-command hardware path supports.

The table is derived from the per-model capability matrix by
``sc_neurocore.studio.hardware_path.supported_models``; nothing in it is kept
by hand. It records the model-level verdict, which does not depend on the
tools of the host that renders it: a model is supported when it compiles and a
bit-true C kernel mirrors at least one integrator and format.

Usage::

    python tools/hardware_path_support.py --write
    python tools/hardware_path_support.py --check

Deriving the whole catalogue takes several minutes, because the capability
matrix computes each model's numeric contract at every Studio format.
``--models`` restricts the table to the named models (with ``--output``, for
a quick look elsewhere than the tracked file).
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = REPO_ROOT / "docs" / "_generated" / "hardware_path_support.md"

_HEADER = """\
<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->
<!-- Commercial license available -->
<!-- © Concepts 1996–2026 Miroslav Šotek. All rights reserved. -->
<!-- © Code 2020–2026 Miroslav Šotek. All rights reserved. -->
<!-- ORCID: 0009-0009-3560-0851 -->
<!-- Contact: www.anulum.li | protoscience@anulum.li -->
<!-- SC-NeuroCore — Hardware path supported set -->
<!-- Generated by tools/hardware_path_support.py; do not edit by hand. -->
"""


def render_support(rows: Sequence[Mapping[str, Any]]) -> str:
    """Render the supported-set table.

    Parameters
    ----------
    rows : Sequence of Mapping
        Rows as ``supported_models`` returns them.

    Returns
    -------
    str
        The Markdown document: counts, requirements and one row per model.
    """
    supported = [row for row in rows if row["model_supported"]]
    refused = Counter(
        f"{row['model_refusal']['operation']}: {row['model_refusal']['reason']}"
        for row in rows
        if not row["model_supported"]
    )
    lines = [
        _HEADER,
        "# Hardware path supported set",
        "",
        "`sc-neurocore hardware-path MODEL -o DIR` (Python:",
        "`sc_neurocore.studio.hardware_path.run_hardware_path`) runs a catalogue",
        "model through its capability gate, RTL, bit-exact co-simulation against the",
        "bit-true C kernel, guarantee summary and synthesis. This table is derived",
        "from the per-model capability matrix: a model is supported when it compiles",
        "and a bit-true C kernel mirrors at least one integrator and Q format.",
        "",
        "On a host the path also needs Icarus Verilog (`iverilog`, `vvp`), a C",
        "compiler (`gcc`) and Yosys; it refuses at its first stage when one is",
        "missing. Place and route runs for `ice40` and `ecp5` when the target's",
        "nextpnr is installed and is recorded as not run otherwise; `gowin` and",
        "`xilinx` are synthesised only. `sc-neurocore hardware-path --list` gives the",
        "verdict for the host it runs on.",
        "",
        f"Models: **{len(rows)}**; supported: **{len(supported)}**; "
        f"refused: **{len(rows) - len(supported)}**.",
        "",
        "## Refusal reasons",
        "",
        "| Models | Operation: reason |",
        "| ---: | --- |",
    ]
    lines.extend(f"| {count} | {reason} |" for reason, count in sorted(refused.items()))
    lines.extend(
        [
            "",
            "## Models",
            "",
            "| Model | Hardware path | Co-simulated integrator @ format, or refusal |",
            "| --- | --- | --- |",
        ]
    )
    for row in rows:
        if row["model_supported"]:
            detail = ", ".join(
                f"{entry['integrator']} @ {entry['q_format']}" for entry in row["combinations"]
            )
            lines.append(f"| {row['model']} | supported | {detail} |")
        else:
            refusal = row["model_refusal"]
            lines.append(
                f"| {row['model']} | refused | {refusal['operation']}: {refusal['reason']} |"
            )
    return "\n".join(lines) + "\n"


def derive(models: Sequence[str] | None = None) -> str:
    """Derive the table from the checkout's code now.

    Parameters
    ----------
    models : Sequence of str or None, optional
        Models to include; every catalogue model when ``None``.

    Returns
    -------
    str
        The rendered document.
    """
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from sc_neurocore.studio.hardware_path import supported_models

    return render_support(supported_models(models, tool_status={}))


def document_problems(path: Path, rendered: str) -> list[str]:
    """Return why the document at ``path`` is missing or differs from ``rendered``.

    Parameters
    ----------
    path : Path
        The tracked document.
    rendered : str
        The document derived now.

    Returns
    -------
    list of str
        Empty when the document is current.
    """
    if not path.is_file():
        return [f"missing hardware path support table: {path.name}"]
    if path.read_text(encoding="utf-8") != rendered:
        return [
            f"stale hardware path support table: {path.name} "
            "(run tools/hardware_path_support.py --write)"
        ]
    return []


def main(argv: list[str] | None = None) -> int:
    """Write or check the supported-set document.

    Parameters
    ----------
    argv : list of str or None, optional
        Arguments; ``sys.argv`` when ``None``.

    Returns
    -------
    int
        Zero when written or current; one when ``--check`` finds it stale or missing.
    """
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the document")
    mode.add_argument("--check", action="store_true", help="fail if the document is stale")
    parser.add_argument("--output", type=Path, default=DOCUMENT, help="document path")
    parser.add_argument(
        "--models", default=None, help="comma-separated models (default: the whole catalogue)"
    )
    args = parser.parse_args(argv)
    models = [name for name in args.models.split(",") if name] if args.models else None
    rendered = derive(models)
    if args.write:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
        print(f"Wrote {args.output}")
        return 0
    problems = document_problems(args.output, rendered)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
