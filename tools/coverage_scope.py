# SC-NeuroCore — Coverage scope: what the coverage gate measures and what it omits

"""State the scope of the coverage gate from the coverage configuration itself.

The coverage threshold applies to the files the configuration measures, not to
the whole package. This tool reads the omission patterns from ``pyproject.toml``,
counts the package's Python source files and lines that each pattern removes
from the measurement, and writes that as a block of ``VALIDATION.md``. With
``--check`` it fails when the committed block differs, so the document cannot
describe omissions the configuration no longer has, or miss ones it has.

A line count here is the number of physical lines of a file. It says how much
source the gate does not look at; it is not a count of executable statements.
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from dataclasses import dataclass
from fnmatch import fnmatchcase
from pathlib import Path
import subprocess
import sys

if sys.version_info >= (3, 11):
    import tomllib
else:
    import tomli as tomllib

BEGIN = "<!-- coverage-scope:begin (generated by tools/coverage_scope.py; do not edit) -->"
END = "<!-- coverage-scope:end -->"
DOCUMENT = Path("VALIDATION.md")
CONFIGURATION = Path("pyproject.toml")


@dataclass(frozen=True)
class Omission:
    """One omission pattern and the source it removes from the measurement."""

    pattern: str
    files: int
    lines: int


@dataclass(frozen=True)
class Scope:
    """Measured and omitted source of the package under the coverage gate."""

    package: str
    files: int
    lines: int
    omitted_files: int
    omitted_lines: int
    omissions: tuple[Omission, ...]


def read_scope(root: Path) -> Scope:
    """Count what the coverage configuration measures and what it omits.

    Parameters
    ----------
    root : Path
        Repository root holding ``pyproject.toml`` and the source tree.

    Returns
    -------
    Scope
        Totals of the package and one row per omission pattern, in the order
        of the configuration. A file matched by two patterns is counted in
        each row and once in the omitted totals.

    Raises
    ------
    ValueError
        The configuration names no single source directory or no omission
        list, or the source directory holds no Python file.
    """
    configuration = tomllib.loads((root / CONFIGURATION).read_text(encoding="utf-8"))
    run = configuration.get("tool", {}).get("coverage", {}).get("run", {})
    directories, patterns = run.get("source_dirs"), run.get("omit")
    if not isinstance(directories, list) or len(directories) != 1:
        raise ValueError("Coverage configuration must name exactly one source directory.")
    if not isinstance(patterns, list) or not all(isinstance(item, str) for item in patterns):
        raise ValueError("Coverage configuration has no omission list.")
    files = source_files(root, directories[0])
    if not files:
        raise ValueError("Coverage source directory holds no Python file.")
    sizes = {
        path.relative_to(root).as_posix(): len(path.read_bytes().splitlines()) for path in files
    }
    omitted: set[str] = set()
    rows: list[Omission] = []
    for pattern in patterns:
        matched = [name for name in sizes if fnmatchcase(name, pattern)]
        omitted.update(matched)
        rows.append(Omission(pattern, len(matched), sum(sizes[name] for name in matched)))
    return Scope(
        package=directories[0],
        files=len(sizes),
        lines=sum(sizes.values()),
        omitted_files=len(omitted),
        omitted_lines=sum(sizes[name] for name in omitted),
        omissions=tuple(rows),
    )


def source_files(root: Path, directory: str) -> list[Path]:
    """List the Python source files of the package that belong to the repository.

    Parameters
    ----------
    root : Path
        Repository root.
    directory : str
        Source directory of the package, relative to the root.

    Returns
    -------
    list of Path
        In a Git work tree, the tracked ``.py`` files under the directory, so
        that build products and local leftovers do not change the counts
        between one checkout and another. Outside a work tree, every ``.py``
        file under the directory except interpreter caches.
    """
    listed = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--", directory],
        capture_output=True,
        check=False,
        timeout=60,
    )
    if listed.returncode == 0 and listed.stdout:
        names = listed.stdout.decode("utf-8").rstrip("\0").split("\0")
        return sorted(root / name for name in names if name.endswith(".py"))
    return sorted(
        path for path in (root / directory).rglob("*.py") if "__pycache__" not in path.parts
    )


def render(scope: Scope) -> str:
    """Write the scope as the Markdown block of the validation document.

    Parameters
    ----------
    scope : Scope
        Counts returned by :func:`read_scope`.

    Returns
    -------
    str
        The block from its begin marker to its end marker, without a
        trailing newline.
    """
    measured_files = scope.files - scope.omitted_files
    measured_lines = scope.lines - scope.omitted_lines
    share = 100.0 * measured_lines / scope.lines
    lines = [
        BEGIN,
        "",
        f"The coverage threshold applies to {measured_files:,} of {scope.files:,} Python files under",
        f"`{scope.package}` ({measured_lines:,} of {scope.lines:,} source lines, {share:.1f} %). The remaining",
        f"{scope.omitted_files:,} files ({scope.omitted_lines:,} lines) are omitted by the patterns below and are not part of",
        "the percentage. An omitted file may still have tests; the gate does not measure them.",
        "",
        "| Omission pattern | Files | Source lines |",
        "| --- | ---: | ---: |",
    ]
    lines += [f"| `{row.pattern}` | {row.files:,} | {row.lines:,} |" for row in scope.omissions]
    lines += ["", END]
    return "\n".join(lines)


def replace_block(document: str, block: str) -> str:
    """Return the document with the generated block replaced.

    Parameters
    ----------
    document : str
        Current text of the validation document.
    block : str
        Newly rendered block.

    Returns
    -------
    str
        The document with the text between the markers replaced.

    Raises
    ------
    ValueError
        The document does not hold exactly one begin and one end marker in
        that order.
    """
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise ValueError("Validation document must hold exactly one coverage-scope block.")
    head, rest = document.split(BEGIN)
    if END not in rest:
        raise ValueError("Coverage-scope markers are out of order.")
    return head + block + rest.split(END, 1)[1]


def main(argv: Sequence[str] | None = None) -> int:
    """Write the coverage-scope block, or check that the committed one is current.

    Parameters
    ----------
    argv : sequence of str, optional
        Command-line arguments; the process arguments when omitted.

    Returns
    -------
    int
        Zero when the block was written or is current, one when ``--check``
        finds a difference, two when the inputs cannot be read.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    path = arguments.repo / DOCUMENT
    try:
        current = path.read_text(encoding="utf-8")
        updated = replace_block(current, render(read_scope(arguments.repo)))
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 2
    if arguments.check:
        if updated != current:
            print(
                "VALIDATION.md coverage scope is out of date; run tools/coverage_scope.py",
                file=sys.stderr,
            )
            return 1
        return 0
    path.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
