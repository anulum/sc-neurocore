//! MLIR CIRCT emitter for SC IR graphs.
//!
//! Produces CIRCT-compatible MLIR text using hw/comb/seq dialects.

use crate::ir::graph::*;

mod divide;
mod primitives;
mod runtime_check;
mod state;
mod word;

/// Emit CIRCT-compatible MLIR from an SC graph.
pub fn emit(graph: &ScGraph) -> Result<String, String> {
    crate::ir::verify::verify(graph).map_err(|errors| {
        errors
            .iter()
            .map(ToString::to_string)
            .collect::<Vec<_>>()
            .join("\n")
    })?;
    let mut mlir = String::new();

    mlir.push_str(&format!(
        "// Auto-generated by SC-NeuroCore MLIR Emitter v3.11\n\
         // Source graph: {}\n\n",
        graph.name
    ));

    // Module header with ports
    let mut ports = Vec::new();
    ports.push("in %clk: i1".to_string());
    ports.push("in %rst_n: i1".to_string());

    for op in &graph.ops {
        match op {
            ScOp::Input { name, ty, .. } => {
                ports.push(format!("in %{name}: i{}", ty.bit_width()));
            }
            ScOp::Output { name, source, .. } => {
                ports.push(format!(
                    "out {name}: i{}",
                    crate::ir::emit_sv::find_value_width(graph, *source)
                ));
            }
            _ => {}
        }
    }

    if graph.ops.iter().any(|op| matches!(op, ScOp::Check { .. })) {
        mlir.push_str(&format!(
            "sv.macro.decl @{}__sc_synthesis [\"SYNTHESIS\"]\n",
            graph.name
        ));
    }
    mlir.push_str(&format!(
        "hw.module @{}({}) {{\n",
        graph.name,
        ports.join(", ")
    ));

    mlir.push_str("  %sc_clock = seq.to_clock %clk\n  %sc_one = hw.constant 1 : i1\n  %sc_reset = comb.xor %rst_n, %sc_one : i1\n");

    for op in &graph.ops {
        if primitives::emit(&mut mlir, graph, op)? {
            continue;
        }
        match op {
            ScOp::State { id, initial, ty } => state::emit(&mut mlir, graph, *id, *initial, ty)?,
            ScOp::Store { .. } => {}
            ScOp::Check {
                id,
                condition,
                enable,
                kind,
            } => runtime_check::emit(&mut mlir, graph, *id, *condition, *enable, *kind),
            ScOp::Word { id, op } => word::emit(&mut mlir, graph, *id, op)?,
            ScOp::Input { .. } | ScOp::Output { .. } => {}
            ScOp::Encode { .. }
            | ScOp::BitwiseAnd { .. }
            | ScOp::BitwiseXor { .. }
            | ScOp::Constant { .. }
            | ScOp::Popcount { .. }
            | ScOp::Decode { .. }
            | ScOp::DivConst { .. } => {}
            ScOp::LifStep {
                id,
                current,
                params,
                ..
            } => {
                let cur = value_wire(graph, *current);
                mlir.push_str(&format!(
                    "  %v{id}_spike, %v{id}_v = hw.instance \"lif_{id}\" \
                     @sc_lif_neuron<DATA_WIDTH: i32 = {dw}, V_THRESHOLD: i32 = {vt}>(\
                     clk: %clk: i1, rst_n: %rst_n: i1, I_t: {cur}: i1) -> \
                     (spike_out: i1, v_out: i{dw})\n",
                    id = id.0,
                    dw = params.data_width,
                    vt = params.v_threshold,
                    cur = cur,
                ));
            }
            ScOp::DenseForward { id, params, .. } => {
                mlir.push_str(&format!(
                    "  %v{} = hw.instance \"dense_{}\" @sc_dense_layer_core<\
                     N_INPUTS: i32 = {}, N_NEURONS: i32 = {}>(\
                     clk: %clk: i1, rst_n: %rst_n: i1) -> (spikes: i{})\n",
                    id.0, id.0, params.n_inputs, params.n_neurons, params.n_neurons
                ));
            }
            ScOp::DclsLayer { id, params, .. } => {
                mlir.push_str(&format!(
                    "  %v{} = hw.instance \"dcls_{}\" @sc_dcls_layer_core<\
                     N_TAPS: i32 = {}, DATA_WIDTH: i32 = {}, FRACTION: i32 = {}>(\
                     clk: %clk: i1, rst_n: %rst_n: i1) -> (weighted_sum_q88: i{})\n",
                    id.0,
                    id.0,
                    params.n_taps,
                    params.data_width,
                    params.fraction,
                    params.data_width
                ));
            }
            ScOp::GraphForward {
                id,
                features,
                adjacency,
                n_nodes,
                n_features,
            } => {
                let features_w = value_wire(graph, *features);
                let adjacency_w = value_wire(graph, *adjacency);
                mlir.push_str(&format!(
                    "  %v{id} = hw.instance \"graph_{id}\" @sc_graph_forward<\
                     N_NODES: i32 = {n_nodes}, N_FEATURES: i32 = {n_features}>(\
                     features: {features_w}: i64, adjacency: {adjacency_w}: i64) \
                     -> (agg: i64)\n",
                    id = id.0,
                ));
            }
            ScOp::SoftmaxAttention { id, q, k, v, dim_k } => {
                let q_w = value_wire(graph, *q);
                let k_w = value_wire(graph, *k);
                let v_w = value_wire(graph, *v);
                mlir.push_str(&format!(
                    "  %v{id} = hw.instance \"softmax_{id}\" @sc_softmax_attention<\
                     DIM_K: i32 = {dim_k}>(\
                     q_in: {q_w}: i64, k_in: {k_w}: i64, v_in: {v_w}: i64) \
                     -> (attn_out: i64)\n",
                    id = id.0,
                ));
            }
            ScOp::KuramotoStep {
                id,
                phases,
                omega,
                coupling,
                dt,
            } => {
                let phases_w = value_wire(graph, *phases);
                let omega_w = value_wire(graph, *omega);
                let coupling_w = value_wire(graph, *coupling);
                let dt_fixed = (*dt * 65536.0).round() as i64;
                mlir.push_str(&format!(
                    "  %v{id} = hw.instance \"kuramoto_{id}\" @sc_kuramoto_step<\
                     DT_FIXED: i32 = {dt}>(\
                     phases_in: {phases_w}: i64, omega: {omega_w}: i64, \
                     coupling: {coupling_w}: i64) -> (phases_out: i64)\n",
                    id = id.0,
                    dt = dt_fixed,
                ));
            }
            ScOp::Scale { id, input, factor } => {
                let inp = value_wire(graph, *input);
                let scale_int = (*factor * 256.0) as i64;
                mlir.push_str(&format!(
                    "  %v{} = comb.mul {inp}, %c_scale_{id} : i16\n",
                    id.0,
                    inp = inp,
                    id = id.0,
                ));
                let _ = scale_int; // used in constant emission
            }
            ScOp::Offset { id, input, offset } => {
                let inp = value_wire(graph, *input);
                let _ = offset;
                mlir.push_str(&format!(
                    "  %v{} = comb.add {inp}, %c_off_{id} : i16\n",
                    id.0,
                    inp = inp,
                    id = id.0,
                ));
            }
            ScOp::Reduce { id, input, mode } => {
                let inp = value_wire(graph, *input);
                let op_name = match mode {
                    ReduceMode::Sum => "add",
                    ReduceMode::Max => "max",
                };
                mlir.push_str(&format!("  %v{} = comb.{op_name} {inp} : i64\n", id.0,));
            }
        }
    }

    // HW modules terminate with one aggregate output, including the empty tuple.
    let mut results = Vec::new();
    let mut result_types = Vec::new();
    for op in &graph.ops {
        if let ScOp::Output { source, .. } = op {
            results.push(value_wire(graph, *source));
            result_types.push(format!(
                "i{}",
                crate::ir::emit_sv::find_value_width(graph, *source)
            ));
        }
    }
    if results.is_empty() {
        mlir.push_str("  hw.output\n");
    } else {
        mlir.push_str(&format!(
            "  hw.output {} : {}\n",
            results.join(", "),
            result_types.join(", ")
        ));
    }
    mlir.push_str("}\n");
    Ok(mlir)
}

fn value_wire(graph: &ScGraph, id: ValueId) -> String {
    for op in &graph.ops {
        if op.result_id() == id {
            return match op {
                ScOp::Input { name, .. } => format!("%{name}"),
                ScOp::Constant { id, .. } => format!("%c{}", id.0),
                ScOp::LifStep { id, .. } => format!("%v{}_spike", id.0),
                ScOp::DenseForward { id, .. } => format!("%v{}", id.0),
                _ => format!("%v{}", id.0),
            };
        }
    }
    format!("%v{}", id.0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::builder::ScGraphBuilder;

    #[test]
    fn basic_and_gate_emits_mlir() {
        let mut b = ScGraphBuilder::new("test_and");
        let a = b.input("a", ScType::Bool);
        let bv = b.input("b", ScType::Bool);
        let c = b.bitwise_and(a, bv);
        b.output("out", c);
        let graph = b.build();

        let mlir = emit(&graph).unwrap();
        assert!(mlir.contains("hw.module @test_and"));
        assert!(mlir.contains("comb.and"));
        assert!(mlir.contains("hw.output"));
    }

    #[test]
    fn module_wrapping() {
        let mut b = ScGraphBuilder::new("wrapper");
        let x = b.input("x", ScType::Bool);
        b.output("y", x);
        let graph = b.build();

        let mlir = emit(&graph).unwrap();
        assert!(mlir.starts_with("// Auto-generated"));
        assert!(mlir.contains("hw.module @wrapper"));
        assert!(mlir.ends_with("}\n"));
    }

    #[test]
    fn xor_gate() {
        let mut b = ScGraphBuilder::new("test_xor");
        let a = b.input("a", ScType::Bool);
        let bv = b.input("b", ScType::Bool);
        let c = b.bitwise_xor(a, bv);
        b.output("out", c);
        let graph = b.build();

        let mlir = emit(&graph).unwrap();
        assert!(mlir.contains("comb.xor"));
    }
}
