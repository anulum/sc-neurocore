"""Focused suite: TestVerilogSyntax from former test_equation_compiler.py."""

from __future__ import annotations

from sc_neurocore.compiler.equation_compiler import (
    compile_to_verilog,
    equation_to_fpga,
)
from sc_neurocore.neurons.equation_builder import (
    EquationNeuron,
)


class TestVerilogSyntax:
    """The structure of the generated Verilog."""

    def test_module_structure(self) -> None:
        """The module has balanced blocks and a timescale."""
        _, verilog = equation_to_fpga(
            "dv/dt = I",
            init={"v": 0.0},
            module_name="syntax_check",
        )
        # Check module/endmodule
        assert verilog.count("endmodule") == 1
        # begin/end balance (endmodule contains "end", so subtract 1)
        assert verilog.count("begin") == verilog.count("end") - 1
        # Has timescale
        assert "`timescale" in verilog
        # Has always block
        assert "always @(posedge clk" in verilog

    def test_auto_generated_comment(self) -> None:
        """The module says it was generated."""
        _, verilog = equation_to_fpga(
            "dv/dt = I",
            init={"v": 0.0},
        )
        assert "Auto-generated by SC-NeuroCore" in verilog

    def test_custom_data_width(self) -> None:
        """A custom data width sets the register width."""
        neuron = EquationNeuron(
            equations={"v": "I"},
            state={"v": 0.0},
            dt=1.0,
        )
        verilog = compile_to_verilog(neuron, data_width=32, fraction=16)
        assert "[31:0]" in verilog
